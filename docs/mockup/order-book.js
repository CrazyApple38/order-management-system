// cellData[ri][d] は配列。常に配列として返す。
function getCellEntries(ri, d) {
    const cell = cellData[ri] && cellData[ri][d];
    if (!cell) return [];
    return Array.isArray(cell) ? cell : [cell];
}

function getCellTotalCount(ri, d) {
    return getCellEntries(ri, d).reduce((sum, e) => sum + (e.count || 0), 0);
}

function obReadAutoGeneratedOrders() {
    if (window.OmsMockStore) return window.OmsMockStore.getAutoGeneratedOrders();
    try {
        const raw = localStorage.getItem(OB_AUTO_ORDER_STORAGE_KEY);
        const parsed = raw ? JSON.parse(raw) : [];
        return Array.isArray(parsed) ? parsed : [];
    } catch (_) {
        return [];
    }
}

function obStripAutoGeneratedRows() {
    const keptRows = [];
    const keptCellData = {};
    sampleRows.forEach((row, oldIdx) => {
        if (row && row.isAutoGenerated) return;
        const newIdx = keptRows.length;
        keptRows.push(row);
        if (cellData[oldIdx]) keptCellData[newIdx] = cellData[oldIdx];
    });
    sampleRows = keptRows;
    cellData = keptCellData;
}

function obAutoGeneratedRowKey(order) {
    return [
        order.branch || order.employeeGcName || '',
        order.category || '応援交通',
        order.shift || '昼',
        order.company || '',
        order.task || ''
    ].join('|');
}

function obApplyAutoGeneratedOrders() {
    obStripAutoGeneratedRows();
    const orders = obReadAutoGeneratedOrders();
    const grouped = new Map();

    orders.forEach(order => {
        if (!order || !order.isAutoGenerated) return;
        const key = obAutoGeneratedRowKey(order);
        if (!grouped.has(key)) grouped.set(key, []);
        grouped.get(key).push(order);
    });

    grouped.forEach((groupOrders, key) => {
        const first = groupOrders[0];
        const sourceSiteIds = [...new Set(groupOrders.map(o => o.sourceSiteId).filter(Boolean))];
        const sourceEmployeeIds = [...new Set(groupOrders.map(o => o.sourceEmployeeId).filter(Boolean))];
        const employeeNames = [...new Set(groupOrders.map(o => o.employeeName).filter(Boolean))];
        const row = {
            _rowId: 'auto:' + key,
            branch: first.branch || first.employeeGcName || '',
            category: first.category || '応援交通',
            shift: first.shift || '昼',
            company: first.company || '',
            task: first.task || '',
            hidden: false,
            isAutoGenerated: true,
            sourceSiteId: sourceSiteIds.join('|'),
            sourceEmployeeId: sourceEmployeeIds.join('|'),
            sourceDate: first.sourceDate || '',
            employeeName: employeeNames.join('、')
        };
        const ri = sampleRows.length;
        sampleRows.push(row);

        groupOrders.forEach(order => {
            const m = (order.sourceDate || '').match(/^(\d{4})-(\d{2})-(\d{2})$/);
            if (!m || parseInt(m[1], 10) !== currentYear || parseInt(m[2], 10) !== currentMonth) return;
            const day = parseInt(m[3], 10);
            if (!cellData[ri]) cellData[ri] = {};
            if (!cellData[ri][day]) {
                cellData[ri][day] = [{
                    count: 0,
                    confidence: 'confirmed',
                    confidenceManual: false,
                    subTasks: [],
                    dailyTaskName: row.task,
                    startTime: '',
                    endTime: '',
                    supervisor: '',
                    supervisorTel: '',
                    assignment: '',
                    mapUrl: '',
                    badge: null,
                    remarks: 'SL配置から自動生成',
                    meetingPlace: '',
                    meetingTime: '',
                    isAutoGenerated: true,
                    sourceSiteId: row.sourceSiteId,
                    sourceEmployeeId: ''
                }];
            }
            const entry = cellData[ri][day][0];
            const names = entry.assignment ? entry.assignment.split('、').filter(Boolean) : [];
            if (order.employeeName && !names.includes(order.employeeName)) names.push(order.employeeName);
            entry.assignment = names.join('、');
            entry.count = names.length || entry.count + 1;
            entry.sourceEmployeeId = [...new Set(
                (entry.sourceEmployeeId ? entry.sourceEmployeeId.split('|') : [])
                    .concat(order.sourceEmployeeId || [])
                    .filter(Boolean)
            )].join('|');
            entry.sourceSiteId = [...new Set(
                (entry.sourceSiteId ? entry.sourceSiteId.split('|') : [])
                    .concat(order.sourceSiteId || [])
                    .filter(Boolean)
            )].join('|');
        });
    });
    initialSorted = false;
}

// --- 信頼度の自動確定ルール ---
// ルール1: 昨日以前の日付 → 自動的に「確定」（常に適用、手動フラグ無視）
// ルール2: 業務管理計画書で社員が配置されている → 自動的に「確定」（手動フラグがあればスキップ）
function applyAutoConfidence() {
    const today = obGetDemoTodayDate();
    const daysInMonth = new Date(currentYear, currentMonth, 0).getDate();

    sampleRows.forEach((_row, ri) => {
        if (!cellData[ri]) return;
        for (let d = 1; d <= daysInMonth; d++) {
            const entries = getCellEntries(ri, d);
            if (entries.length === 0) continue;

            const cellDate = new Date(currentYear, currentMonth - 1, d);
            cellDate.setHours(0, 0, 0, 0);

            entries.forEach(entry => {
                // ルール1: 昨日以前 → 確定（過去の事実は変わらないため常に適用）
                if (cellDate < today) {
                    entry.confidence = 'confirmed';
                    entry.confidenceManual = false;
                    return;
                }

                // ユーザーが手動で設定した場合はルール2をスキップ
                if (entry.confidenceManual) return;

                // ルール2: 社員が配置済み → 確定
                if (entry.assignment && entry.assignment.trim() !== '') {
                    entry.confidence = 'confirmed';
                }
            });
        }
    });
}

