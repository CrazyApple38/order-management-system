/* ============================================================
   co-mock-store.js — SL / OB 共通モック状態ストア
   ============================================================ */
(function () {
    'use strict';

    var STORE_KEY = 'mock.oms.state.v1';
    var LEGACY_SL_STATE_KEY = 'mock.sl.state.v1';
    var LEGACY_AUTO_ORDER_KEY = 'mock.sl.autoGeneratedOrders.v1';
    var LEGACY_DEFAULT_DATE = '2026-01-27';
    var DEFAULT_DATE = '2026-05-01';

    function clone(v) {
        return v == null ? v : JSON.parse(JSON.stringify(v));
    }

    function readRaw() {
        try {
            var raw = localStorage.getItem(STORE_KEY);
            return raw ? JSON.parse(raw) : null;
        } catch (_) {
            return null;
        }
    }

    function normalize(state) {
        state = state && typeof state === 'object' ? state : {};
        if (state.version !== 1) state.version = 1;
        if (!state.currentDate || state.currentDate === LEGACY_DEFAULT_DATE) state.currentDate = DEFAULT_DATE;
        if (!state.demoToday || state.demoToday === LEGACY_DEFAULT_DATE) state.demoToday = DEFAULT_DATE;
        if (!state.obMonths || typeof state.obMonths !== 'object') state.obMonths = {};
        if (!state.slStates || typeof state.slStates !== 'object') state.slStates = {};
        if (!state.wsWeeks || typeof state.wsWeeks !== 'object') state.wsWeeks = {};
        if (!Array.isArray(state.leaveApplications)) state.leaveApplications = null;
        if (!state.leaveMeta || typeof state.leaveMeta !== 'object') state.leaveMeta = {};
        if (!Array.isArray(state.autoGeneratedOrders)) state.autoGeneratedOrders = [];
        return state;
    }

    function read() {
        return normalize(readRaw());
    }

    function write(state) {
        state = normalize(state);
        state.updatedAt = new Date().toISOString();
        try {
            localStorage.setItem(STORE_KEY, JSON.stringify(state));
        } catch (_) {}
        return state;
    }

    function monthKey(year, month) {
        return String(year) + '-' + String(month).padStart(2, '0');
    }

    function dateToParts(dateKey) {
        var m = String(dateKey || DEFAULT_DATE).match(/^(\d{4})-(\d{2})-(\d{2})$/);
        return m ? { year: +m[1], month: +m[2], day: +m[3] } : { year: 2026, month: 5, day: 1 };
    }

    function pad2(n) {
        return String(n).padStart(2, '0');
    }

    function dateKeyFromDate(d) {
        return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate());
    }

    function dateFromKey(dateKey) {
        var p = dateToParts(dateKey);
        var d = new Date(p.year, p.month - 1, p.day);
        d.setHours(0, 0, 0, 0);
        return d;
    }

    function weekKey(dateKey) {
        var d = dateFromKey(dateKey || DEFAULT_DATE);
        var day = d.getDay();
        var diff = day === 0 ? -6 : 1 - day;
        d.setDate(d.getDate() + diff);
        return dateKeyFromDate(d);
    }

    function setAutoGeneratedOrders(orders) {
        var state = read();
        state.autoGeneratedOrders = Array.isArray(orders) ? clone(orders) : [];
        write(state);
        try {
            localStorage.setItem(LEGACY_AUTO_ORDER_KEY, JSON.stringify(state.autoGeneratedOrders));
        } catch (_) {}
    }

    function getAutoGeneratedOrders() {
        var rawState = readRaw();
        if (rawState && Array.isArray(rawState.autoGeneratedOrders)) return clone(rawState.autoGeneratedOrders);
        try {
            var legacy = JSON.parse(localStorage.getItem(LEGACY_AUTO_ORDER_KEY) || '[]');
            return Array.isArray(legacy) ? legacy : [];
        } catch (_) {
            return [];
        }
    }

    window.OmsMockStore = {
        key: STORE_KEY,
        legacySlStateKey: LEGACY_SL_STATE_KEY,
        legacyAutoOrderKey: LEGACY_AUTO_ORDER_KEY,
        defaultDate: DEFAULT_DATE,
        read: read,
        write: write,
        reset: function () {
            try {
                localStorage.removeItem(STORE_KEY);
                localStorage.removeItem(LEGACY_SL_STATE_KEY);
                localStorage.removeItem(LEGACY_AUTO_ORDER_KEY);
            } catch (_) {}
        },
        resetAndReload: function () {
            if (!confirm('共通ダミーデータを初期状態に戻しますか？\nSL/OB/WS/LAの保存済みモック状態と自動生成行がリセットされます。')) return;
            this.reset();
            location.reload();
        },
        getCurrentDate: function () {
            return read().currentDate || DEFAULT_DATE;
        },
        setCurrentDate: function (dateKey) {
            var state = read();
            state.currentDate = dateKey || DEFAULT_DATE;
            write(state);
        },
        getDemoToday: function () {
            return read().demoToday || DEFAULT_DATE;
        },
        setDemoToday: function (dateKey) {
            var state = read();
            state.demoToday = dateKey || DEFAULT_DATE;
            write(state);
        },
        dateToParts: dateToParts,
        monthKey: monthKey,
        weekKey: weekKey,
        dateKeyFromDate: dateKeyFromDate,
        getObMonth: function (year, month) {
            return clone(read().obMonths[monthKey(year, month)] || null);
        },
        setObMonth: function (year, month, payload) {
            var state = read();
            state.obMonths[monthKey(year, month)] = clone(payload);
            write(state);
        },
        getSlState: function (dateKey) {
            return clone(read().slStates[dateKey || read().currentDate] || null);
        },
        setSlState: function (dateKey, snapshot) {
            var state = read();
            state.slStates[dateKey || state.currentDate] = clone(snapshot);
            write(state);
        },
        getAllSlStates: function () {
            return clone(read().slStates);
        },
        getWsWeek: function (dateKey) {
            return clone(read().wsWeeks[weekKey(dateKey || read().currentDate)] || null);
        },
        setWsWeek: function (dateKey, payload) {
            var state = read();
            state.wsWeeks[weekKey(dateKey || state.currentDate)] = clone(payload);
            write(state);
        },
        getLeaveApplications: function () {
            return clone(read().leaveApplications);
        },
        setLeaveApplications: function (applications, meta) {
            var state = read();
            state.leaveApplications = Array.isArray(applications) ? clone(applications) : [];
            state.leaveMeta = meta && typeof meta === 'object' ? clone(meta) : state.leaveMeta || {};
            write(state);
        },
        getAutoGeneratedOrders: getAutoGeneratedOrders,
        setAutoGeneratedOrders: setAutoGeneratedOrders
    };
})();
